print(string.format("%d %i %u", 42, -42, 42))
print(string.format("%x %X %o", 255, 255, 8))
print(string.format("%5.2f|%-8.3e|%g", 3.14159, 3141.59, 0.0001))
print(string.format("%s %q %s", "a", "b\nc", 12))
print(string.format("%c%c", 65, 97))
print(string.format("%.3s|%10s|%-6s|", "abcdef", "hi", "hi"))
print(string.format("%a", 0.5))
print(string.format("%A", 0.0))
print(string.format("%p", 1) == "(null)")
print(string.format("%%"))
print(string.format("%d", 3.0))
local ok, e = pcall(string.format, "%r", 1)
