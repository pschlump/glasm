-- U3g: string.pack family (the wasm32 size model).
print(string.packsize("h"), string.packsize("i"), string.packsize("l"), string.packsize("T"))
print(string.packsize("j"), string.packsize("f"), string.packsize("d"), string.packsize("n"))
print(string.pack("i2", 1) == "\1\0")
print((string.pack("i4", 0x01020304):gsub(".", function(c) return string.format("%02x", c:byte()) end)))
print(string.unpack("i4", string.pack("i4", -2)))
print(string.unpack("n", string.pack("n", 0.5)))
print(string.unpack("z", "abc\0de") == "abc")
print(select('#', string.unpack("i2i2", "\1\0\2\0")))
local ok, e = pcall(string.pack, "i17", 1)
print(not ok and e:find("out of limits %[1,16%]") ~= nil)
local ok, e = pcall(string.packsize, "z")
print(not ok and e:find("variable%-length format") ~= nil)
print(string.packsize("!xXi16"))
