-- U2b: \u{XXX} escapes (5.3 lexer), values and byte-exact error texts
print("\u{41}\u{42}" == "AB")
print(string.len("\u{7F}"), string.len("\u{80}"))
print("\u{0}" == "\0", "\u{00000000}" == "\0")
print("\u{80}" == "\xC2\x80")
print("\u{800}" == "\xE0\xA0\x80")
print("\u{10000}" == "\xF0\x90\x80\x80")
print("\u{4000000}" == "\xFC\x84\x80\x80\x80\x80")
print("\u{7FFFFFFF}" == "\xFD\xBF\xBF\xBF\xBF\xBF")
-- errors: byte-exact against stock (parse errors compare exactly)
local function lexerror(s)
  local f, m = load('return ' .. s, '@e')
  print(m)
end
