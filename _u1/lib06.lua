-- io deltas: file:write returns the file; *L keeps the newline (5.2)
local path = "u1-io.tmp"
local f = assert(io.open(path, "w"))
assert(f:write("l1\n", "l2\n") == f)
assert(f:write("3") == f)
f:close()
local g = assert(io.open(path, "r"))
print(g:read("*L"))
print(g:read("*l"))
print(g:read("*L"))
print(g:read("*l"))
print(g:read("*l"))
print(g:read("*a") == "")
g:close()
os.remove(path)
print(io.write == nil)
