-- %f frontier patterns and \0 in patterns (5.2)
print(string.gsub("THE (quick) fox", "%f[%a]%a+", function(w) return "<" .. w .. ">" end))
print(string.gsub("hi there", "%f[%s]", "!"))
print(("x"):gsub("%f[%w]", "Y"))
print(string.find("  x", "%f[^%s]"))
print(string.find("the color of the sky is blue", "%f[%a]blue%f[%A]"))
print(string.match("abc", "%f[b]"))
-- \0 in patterns and subjects (5.1 needed %z; 5.2 uses \0 directly)
print(string.find("\0abc\0", "\0abc"))
print(("\0a\0"):gsub("%f[%a]", "X"))
print(string.gsub("a\0b\0c", "%z", "Z"))
print(string.match("k\0v", "k%zv") ~= nil)
